<?php

namespace App\Models;

use Database\Factories\ChatReadFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

/**
 * Per-user read cursor in a channel.
 */
#[Fillable(['channel_id', 'user_id', 'last_read_message_id'])]
class ChatRead extends Model
{
    /** @use HasFactory<ChatReadFactory> */
    use HasFactory;

    public function channel(): BelongsTo
    {
        return $this->belongsTo(ChatChannel::class, 'channel_id');
    }

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function lastReadMessage(): BelongsTo
    {
        return $this->belongsTo(ChatMessage::class, 'last_read_message_id');
    }
}
